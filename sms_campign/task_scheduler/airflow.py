def runs_for_schedule(schedule, limit=40):
    if get_dag(schedule) is None:
        return []
    response = airflow_request(
        "GET",
        f"dags/{schedule.airflow_dag_id}/dagRuns",
        params={"limit": limit, "order_by": "-start_date"},
    )
    runs = response.get("dag_runs", [])
    return [serialize_run(schedule, run) for run in runs]


def serialize_run(schedule, run):
    start = parse_time(run.get("start_date") or run.get("logical_date"))
    end = parse_time(run.get("end_date"))
    state = (run.get("state") or "queued").lower()
    status = {"success": "Success", "failed": "Failed", "running": "Running", "queued": "Queued"}.get(state, "Queued")
    trigger = "Scheduled" if (run.get("run_type") or "").lower() == "scheduled" else "Manual"
    return {
        "id": run["dag_run_id"],
        "scheduleId": schedule.pk,
        "start": int(start.timestamp() * 1000) if start else 0,
        "end": int(end.timestamp() * 1000) if end else None,
        "status": status,
        "trigger": trigger,
        "logs": [],
    }


def parse_time(value):
    if not value:
        return None
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return timezone.make_aware(parsed) if timezone.is_naive(parsed) else parsed
    except (AttributeError, TypeError, ValueError):
        return None


def logs_for_run(schedule, run_id):
    encoded_run_id = quote(run_id, safe="")
    response = airflow_request(
        "GET",
        f"dags/{schedule.airflow_dag_id}/dagRuns/{encoded_run_id}/taskInstances",
        params={"limit": 100},
    )
    logs = []
    for task in response.get("task_instances", []):
        if task.get("state") not in {"running", "success", "failed", "up_for_retry"}:
            continue
        task_id = task.get("task_id")
        try_number = max(1, int(task.get("try_number") or 1))
        content = airflow_request(
            "GET",
            f"dags/{schedule.airflow_dag_id}/dagRuns/{encoded_run_id}/taskInstances/{quote(task_id, safe='')}/logs/{try_number}",
            params={"full_content": "true"},
            raw_text=True,
        )
        fallback = parse_time(task.get("start_date")) or timezone.now()
        for line in content.splitlines():
            if not line.strip():
                continue
            lowered = line.lower()
            level = "ERROR" if "error" in lowered or "exception" in lowered else "WARN" if "warn" in lowered else "INFO"
            logs.append({"ts": int(fallback.timestamp() * 1000), "level": level, "msg": line})
    return logs


def next_run(schedule):
    dag = get_dag(schedule)
    dag = dag or {}
    return parse_time(dag.get("next_dagrun_create_after") or dag.get("next_dagrun"))


def trigger_run(schedule):
    run_id = f"manual__{uuid.uuid4().hex}"
    result = airflow_request(
        "POST",
        f"dags/{schedule.airflow_dag_id}/dagRuns",
        json={"dag_run_id": run_id, "conf": {"source": "safaricom-ui"}},
    )
    return serialize_run(schedule, result)


def set_paused(schedule, paused):
    try:
        return airflow_request(
            "PATCH",
            f"dags/{schedule.airflow_dag_id}",
            json={"is_paused": paused},
        )
    except AirflowError as exc:
        if exc.status_code == 404:
            raise AirflowError(
                f"Airflow has not registered DAG {schedule.airflow_dag_id} yet.",
                404,
            ) from exc
        raise


def delete_dag(schedule):
    result = get_dag(schedule)
    if result is not None:
        airflow_request("DELETE", f"dags/{schedule.airflow_dag_id}")


