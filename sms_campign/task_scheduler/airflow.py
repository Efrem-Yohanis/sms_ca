class AirflowError(Exception):
    def __init__(self, message, status_code=502):
        super().__init__(message)
        self.status_code = status_code


def airflow_request(method, path, *, raw_text=False, **kwargs):
    if not settings.AIRFLOW_API_PASSWORD:
        raise AirflowError("AIRFLOW_API_PASSWORD is not configured.", 503)
    try:
        response = requests.request(
            method,
            f"{settings.AIRFLOW_API_URL}/api/v1/{path.lstrip('/')}",
            auth=(settings.AIRFLOW_API_USERNAME, settings.AIRFLOW_API_PASSWORD),
            timeout=(3, 15),
            **kwargs,
        )
    except requests.RequestException as exc:
        raise AirflowError(f"Airflow API is unavailable: {exc}") from exc
    if response.status_code >= 400:
        message = response.text[:1000] or response.reason
        raise AirflowError(f"Airflow API returned {response.status_code}: {message}", response.status_code)
    if response.status_code == 204 or not response.content:
        if raw_text:
            return ""
        return {}
    if raw_text:
        return response.text
    try:
        return response.json()
    except ValueError as exc:
        raise AirflowError("Airflow API returned invalid JSON.") from exc


def get_dag(schedule):
    try:
        return airflow_request("GET", f"dags/{schedule.airflow_dag_id}")
    except AirflowError as exc:
        if exc.status_code == 404:
            return None
        raise


def dag_file_path(schedule):
    return os.path.join(settings.AIRFLOW_DAGS_DIR, f"{schedule.airflow_dag_id}.py")


def render_dag(schedule):
    payload = {
        "id": schedule.pk,
        "name": schedule.name,
        "task_type": schedule.task_type,
        "code": schedule.code,
        "connection": schedule.connection,
    }
    config_literal = repr(json.dumps(payload))
    start = schedule.start_date.isoformat() if schedule.start_date else "2024-01-01"
    end_date = f"pendulum.parse({schedule.end_date.isoformat()!r})" if schedule.end_date else "None"
    if schedule.schedule_type == Schedule.ScheduleType.MANUAL:
        cadence = "None"
    elif schedule.schedule_type == Schedule.ScheduleType.INTERVAL:
        unit = schedule.interval_unit
        cadence = f"timedelta({unit}={schedule.interval_value})"
    else:
        effective_cron = schedule.effective_cron()
        cadence = (
            "CronTriggerTimetable("
            f"{effective_cron!r}, timezone={schedule.timezone!r})"
        )
    days_of_week = sorted(schedule.days_of_week or [])
    window_start = (
        f"time({schedule.window_start.hour}, {schedule.window_start.minute})"
        if schedule.window_start
        else "None"
    )
    window_end = (
        f"time({schedule.window_end.hour}, {schedule.window_end.minute})"
        if schedule.window_end
        else "None"
    )
    return f'''# Generated by the Django scheduler API. Do not edit directly.
import json
import pendulum
from datetime import time, timedelta
from airflow import DAG
from airflow.hooks.base import BaseHook
from airflow.operators.python import PythonOperator, ShortCircuitOperator
from airflow.timetables.trigger import CronTriggerTimetable

CONFIG = json.loads({config_literal})
TIMEZONE = {schedule.timezone!r}
ALLOWED_DOWS = {days_of_week!r}
WINDOW_START = {window_start}
WINDOW_END = {window_end}
EXCLUDED_DATES = {sorted(schedule.excluded_dates or [])!r}

def allow_run(**context):
    local_run_time = context["logical_date"].in_timezone(TIMEZONE)
    if local_run_time.date().isoformat() in EXCLUDED_DATES:
        return False
    if ALLOWED_DOWS and local_run_time.weekday() not in ALLOWED_DOWS:
        return False
    if WINDOW_START and WINDOW_END:
        local_time = local_run_time.time().replace(tzinfo=None)
        if not WINDOW_START <= local_time <= WINDOW_END:
            return False
    return True

def execute_schedule():
    if CONFIG["task_type"] == "Python":
        namespace = {{"__name__": "__airflow_task__"}}
        exec(compile(CONFIG["code"], CONFIG["name"], "exec"), namespace)
        main = namespace.get("main")
        if callable(main):
            main()
    else:
        hook = BaseHook.get_connection(CONFIG["connection"]).get_hook()
        hook.run(CONFIG["code"])

with DAG(
    dag_id={schedule.airflow_dag_id!r},
    description={schedule.name!r},
    schedule={cadence},
    start_date=pendulum.parse({start!r}, tz={schedule.timezone!r}),
    end_date={end_date},
    catchup=False,
    tags=["managed-by-django"],
    default_args={{
        "owner": {schedule.owner!r},
        "retries": {schedule.retries},
        "retry_delay": timedelta(seconds={schedule.retry_delay}),
    }},
) as dag:
    run_gate = ShortCircuitOperator(
        task_id="schedule_constraints",
        python_callable=allow_run,
    )
    execute = PythonOperator(
        task_id="execute_schedule",
        python_callable=execute_schedule,
    )
    run_gate >> execute
'''


def write_dag(schedule):
    folder = settings.AIRFLOW_DAGS_DIR
    os.makedirs(folder, exist_ok=True)
    destination = dag_file_path(schedule)
    fd, temporary_path = tempfile.mkstemp(prefix=".schedule-", suffix=".tmp", dir=folder, text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            output.write(render_dag(schedule))
        os.chmod(temporary_path, 0o644)
        os.replace(temporary_path, destination)
    except OSError as exc:
        try:
            os.unlink(temporary_path)
        except FileNotFoundError:
            pass
        raise AirflowError(f"Unable to publish Airflow DAG: {exc}", 503) from exc


def remove_dag_file(schedule):
    try:
        os.remove(dag_file_path(schedule))
    except FileNotFoundError:
        pass
    except OSError as exc:
        raise AirflowError(f"Unable to remove Airflow DAG file: {exc}", 503) from exc


def runs_for_schedule(schedule, limit=40):
    if get_dag(schedule) is None:
        return []
    response = airflow_request(
        "GET",
        f"dags/{schedule.airflow_dag_id}/dagRuns",
        params={"limit": limit, "order_by": "-start_date"},
    )
    runs = response.get("dag_runs", [])
    return [serialize_run(schedule, run) for run in runs]


def serialize_run(schedule, run):
    start = parse_time(run.get("start_date") or run.get("logical_date"))
    end = parse_time(run.get("end_date"))
    state = (run.get("state") or "queued").lower()
    status = {"success": "Success", "failed": "Failed", "running": "Running", "queued": "Queued"}.get(state, "Queued")
    trigger = "Scheduled" if (run.get("run_type") or "").lower() == "scheduled" else "Manual"
    return {
        "id": run["dag_run_id"],
        "scheduleId": schedule.pk,
        "start": int(start.timestamp() * 1000) if start else 0,
        "end": int(end.timestamp() * 1000) if end else None,
        "status": status,
        "trigger": trigger,
        "logs": [],
    }


def parse_time(value):
    if not value:
        return None
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return timezone.make_aware(parsed) if timezone.is_naive(parsed) else parsed
    except (AttributeError, TypeError, ValueError):
        return None


def logs_for_run(schedule, run_id):
    encoded_run_id = quote(run_id, safe="")
    response = airflow_request(
        "GET",
        f"dags/{schedule.airflow_dag_id}/dagRuns/{encoded_run_id}/taskInstances",
        params={"limit": 100},
    )
    logs = []
    for task in response.get("task_instances", []):
        if task.get("state") not in {"running", "success", "failed", "up_for_retry"}:
            continue
        task_id = task.get("task_id")
        try_number = max(1, int(task.get("try_number") or 1))
        content = airflow_request(
            "GET",
            f"dags/{schedule.airflow_dag_id}/dagRuns/{encoded_run_id}/taskInstances/{quote(task_id, safe='')}/logs/{try_number}",
            params={"full_content": "true"},
            raw_text=True,
        )
        fallback = parse_time(task.get("start_date")) or timezone.now()
        for line in content.splitlines():
            if not line.strip():
                continue
            lowered = line.lower()
            level = "ERROR" if "error" in lowered or "exception" in lowered else "WARN" if "warn" in lowered else "INFO"
            logs.append({"ts": int(fallback.timestamp() * 1000), "level": level, "msg": line})
    return logs


def next_run(schedule):
    dag = get_dag(schedule)
    dag = dag or {}
    return parse_time(dag.get("next_dagrun_create_after") or dag.get("next_dagrun"))


def trigger_run(schedule):
    run_id = f"manual__{uuid.uuid4().hex}"
    result = airflow_request(
        "POST",
        f"dags/{schedule.airflow_dag_id}/dagRuns",
        json={"dag_run_id": run_id, "conf": {"source": "safaricom-ui"}},
    )
    return serialize_run(schedule, result)


def set_paused(schedule, paused):
    for attempt in range(30):
        try:
            return airflow_request(
                "PATCH",
                f"dags/{schedule.airflow_dag_id}",
                json={"is_paused": paused},
            )
        except AirflowError as exc:
            if exc.status_code != 404:
                raise
            if attempt == 29:
                raise AirflowError(
                    f"Airflow did not register DAG {schedule.airflow_dag_id} after it was written.",
                    503,
                ) from exc
            time.sleep(1)


def delete_dag(schedule):
    result = get_dag(schedule)
    if result is not None:
        airflow_request("DELETE", f"dags/{schedule.airflow_dag_id}")


