def allow_run(**context):
    local_run_time = context["logical_date"].in_timezone(TIMEZONE)
    if local_run_time.date().isoformat() in EXCLUDED_DATES:
        return False
    if ALLOWED_DOWS and local_run_time.weekday() not in ALLOWED_DOWS:
        return False
    if WINDOW_START and WINDOW_END:
        local_time = local_run_time.time().replace(tzinfo=None)
        if not WINDOW_START <= local_time <= WINDOW_END:
            return False
    return True

def execute_schedule():
    if CONFIG["task_type"] == "Python":
        namespace = {{"__name__": "__airflow_task__"}}
        exec(compile(CONFIG["code"], CONFIG["name"], "exec"), namespace)
        main = namespace.get("main")
        if callable(main):
            main()
    else:
        hook = BaseHook.get_connection(CONFIG["connection"]).get_hook()
        run_sql = getattr(hook, "run", None)
        if not callable(run_sql):
            raise TypeError(
                f"Airflow connection '{{CONFIG['connection']}}' does not provide a SQL-capable hook."
            )
        run_sql(CONFIG["code"])

def notify_schedule_event(event, context):
    api_base = os.environ.get("AIRFLOW_DJANGO_API", "").rstrip("/")
    token = os.environ.get("AIRFLOW_SCHEDULER_CALLBACK_TOKEN", "")
    if not api_base or not token:
        LOGGER.warning("Task scheduler notification callback is not configured.")
        return
    run = context.get("dag_run")
    run_id = getattr(run, "run_id", "") if run else context.get("run_id", "")
    payload = json.dumps({{"event": event, "runId": run_id}}).encode("utf-8")
    request = urllib.request.Request(
        f"{{api_base}}/task-scheduler/schedules/{{quote(CONFIG['id'], safe='')}}/notifications/",
        data=payload,
        headers={{
            "Content-Type": "application/json",
            "X-Task-Scheduler-Token": token,
        }},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=5) as response:
            if response.status >= 300:
                LOGGER.warning("Task scheduler notification returned HTTP %s.", response.status)
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        LOGGER.warning("Unable to deliver task scheduler notification: %s", exc)

